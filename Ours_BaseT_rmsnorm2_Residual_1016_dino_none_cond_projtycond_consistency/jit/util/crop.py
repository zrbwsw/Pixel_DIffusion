import numpy as np
from PIL import Image


def center_crop_arr(pil_image, image_size):
    """
    Deterministic center crop from ADM. The same implementation is exposed by
    EDM2 as ``--transform=center-crop-dhariwal``; using ``image_size=512``
    therefore matches PixelDiT's published ImageNet-512 geometry pipeline.
    https://github.com/openai/guided-diffusion/blob/8fb3ad9197f16bbc40620447b2742e13458d2831/guided_diffusion/image_datasets.py#L126
    https://github.com/NVlabs/edm2/blob/main/dataset_tool.py
    """
    while min(*pil_image.size) >= 2 * image_size:
        pil_image = pil_image.resize(
            tuple(x // 2 for x in pil_image.size), resample=Image.BOX
        )

    scale = image_size / min(*pil_image.size)
    pil_image = pil_image.resize(
        tuple(round(x * scale) for x in pil_image.size), resample=Image.BICUBIC
    )

    arr = np.array(pil_image)
    crop_y = (arr.shape[0] - image_size) // 2
    crop_x = (arr.shape[1] - image_size) // 2
    return Image.fromarray(arr[crop_y: crop_y + image_size, crop_x: crop_x + image_size])
